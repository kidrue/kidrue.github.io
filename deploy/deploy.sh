#!/usr/bin/env bash
set -Eeuo pipefail
umask 077
deploy_path=${1:?缺少部署目录}
project=${2:?缺少 Compose 项目名}
revision=${3:?缺少版本}
incoming=${4:?缺少发布包目录}
platform=${5:?缺少平台}
[[ "$deploy_path" =~ ^/[a-zA-Z0-9_/-]+$ && "$deploy_path" != / && "$deploy_path" != *mew[Cc]at* && "$deploy_path" != *//* ]]
[[ "$project" =~ ^kidrue-blog[a-z0-9_-]*$ && "$revision" =~ ^[a-f0-9]{40}$ ]]
[[ "$incoming" =~ ^/tmp/kidrue-blog-[0-9]+-[0-9]+$ && ! -L "$incoming" ]]
[[ "$platform" = linux/amd64 || "$platform" = linux/arm64 ]]
if [[ $(id -u) != 0 ]]; then exec sudo -n bash "$0" "$@"; fi
for tool in docker nginx certbot curl flock sha256sum ss tar gzip realpath; do command -v "$tool" >/dev/null || { echo "缺少服务器工具：$tool" >&2; exit 1; }; done
nginx -t
systemctl is-active --quiet nginx || { echo '现有 Nginx 服务未运行，请先恢复入口服务。' >&2; exit 1; }
docker compose version
docker info --format '{{.ServerVersion}}' >/dev/null
architecture=$(uname -m)
[[ "$platform:$architecture" = linux/amd64:x86_64 || "$platform:$architecture" = linux/arm64:aarch64 ]] || { echo '镜像架构与服务器不一致' >&2; exit 1; }
[[ ! -L "$deploy_path" && "$(realpath -m "$deploy_path")" = "$deploy_path" ]]
if [[ -d "$deploy_path" ]] && [[ -n "$(ls -A "$deploy_path")" ]]; then
  test -f "$deploy_path/.kidrue-project" && test "$(cat "$deploy_path/.kidrue-project")" = "$project" || { echo '目标部署目录已有非本项目内容，拒绝覆盖。' >&2; exit 1; }
fi
install -d -m 700 "$deploy_path/.deploy/releases" "$deploy_path/.deploy/backups"
archive_kb=$(du -k "$incoming/release.tar.gz" | awk '{print $1}')
available_kb=$(df -Pk "$deploy_path" | awk 'NR == 2 {print $4}')
required_kb=$(( archive_kb * 6 + 1048576 ))
[[ "$available_kb" -ge "$required_kb" ]] || { echo "可用磁盘空间不足，需要至少 ${required_kb} KiB；尚未停止任何服务。" >&2; exit 1; }
exec 9> "$deploy_path/.deploy.lock"
flock -w 1800 9 || { echo '等待博客部署锁超时' >&2; exit 1; }
if [[ ! -f "$deploy_path/.kidrue-project" ]]; then
  if docker ps -a --filter "label=com.docker.compose.project=$project" --format '{{.ID}}' | grep -q .; then echo 'Compose 项目名已有容器，请核对归属' >&2; exit 1; fi
  if docker volume ls --filter "label=com.docker.compose.project=$project" --format '{{.Name}}' | grep -q .; then echo 'Compose 项目名已有数据卷，请核对归属' >&2; exit 1; fi
  printf '%s' "$project" > "$deploy_path/.kidrue-project"
fi
release="$deploy_path/.deploy/releases/$(basename "$incoming")"
test ! -e "$release"
mkdir -m 700 "$release"
backup="$deploy_path/.deploy/backups/$(basename "$incoming")"
install -d -m 700 "$backup"
legacy_healthy=false
app_stopped=false
migration_started=false
if curl -fsS --max-time 5 http://127.0.0.1:3000/health >/dev/null; then legacy_healthy=true; fi
finish() {
  result=$?
  rm -f -- "$incoming/runtime.json"
  if [[ $result != 0 ]]; then
    echo "博客部署失败；发布目录：$release；备份：$backup。成功发布指针未更新；请检查迁移状态后恢复。" >&2
    if [[ -f "$release/nginx.previous" ]]; then
      cp -a "$release/nginx.previous" /etc/nginx/conf.d/kidrue-blog.conf
      if nginx -t; then systemctl reload nginx; fi
    fi
    if [[ "$app_stopped" = true && "$migration_started" = false && -n "${previous_dir:-}" ]]; then
      echo '数据库迁移尚未开始，恢复原博客 API。' >&2
      "${old[@]}" up -d --no-build --wait --wait-timeout 120 api || echo '原博客 API 自动恢复失败，请使用备份中的发布配置检查。' >&2
    fi
  fi
  if [[ "$legacy_healthy" = true ]]; then curl -fsS --max-time 5 http://127.0.0.1:3000/health >/dev/null || echo '现有 mewCat 健康检查异常，请检查服务器状态；脚本未操作其容器。' >&2; fi
}
trap finish EXIT
IFS= read -r runtime_json
printf '%s' "$runtime_json" > "$release/runtime.json"
unset runtime_json
cp "$incoming/compose.production.yaml" "$incoming/site.sh" "$incoming/cleanup-images.sh" "$release/"
gzip -dc "$incoming/images.tar.gz" | docker load
for role in api web tools postgres; do docker image inspect "kidrue-blog-$role:$revision" >/dev/null; done
for role in api web tools postgres; do printf 'kidrue-blog-%s:%s\n' "$role" "$revision"; done >> "$deploy_path/.deploy/imported-images"
previous=()
previous_dir=
if [[ -L "$deploy_path/.deploy/current" ]]; then
  previous_dir=$(readlink -f "$deploy_path/.deploy/current")
  [[ "$previous_dir" = "$deploy_path/.deploy/releases/"* ]]
  cp -a "$previous_dir" "$backup/previous-release"
  previous=(-v "$previous_dir:/previous:ro")
fi
if [[ -s "$deploy_path/.deploy/database/runtime.json" ]]; then
  docker volume inspect "${project}_postgres" >/dev/null || { echo '既有 PostgreSQL 数据卷缺失，拒绝自动创建空库。' >&2; exit 1; }
  previous=(-v "$deploy_path/.deploy/database:/previous:ro")
fi
render() {
  args=(/release "${1:-127.0.0.1}")
  if [[ ${#previous[@]} -gt 0 ]]; then args+=(/previous); fi
  docker run --rm --user 0 -v "$release:/release" "${previous[@]}" "kidrue-blog-tools:$revision" node scripts/deploy/runtime.mjs "${args[@]}"
}
render
# Generated by runtime.mjs from validated scalar values, never user shell input.
# shellcheck source=/dev/null
source "$release/settings.env"
printf 'BLOG_IMAGE_TAG=%s\nBLOG_WEB_PORT=%s\nBLOG_API_PORT=%s\n' "$revision" "$BLOG_WEB_PORT" "$BLOG_API_PORT" > "$release/image.env"
dc=(docker compose --project-directory "$deploy_path" --env-file "$release/image.env" -p "$project" -f "$release/compose.production.yaml" -f "$release/runtime.compose.json")
"${dc[@]}" config --quiet
# Abort on foreign port owners. Existing containers must belong to this project.
for role in api web; do
  if [[ "$role" = api ]]; then port=$BLOG_API_PORT; else port=$BLOG_WEB_PORT; fi
  if ss -H -lnt "sport = :$port" | grep -q .; then
    existing=$(docker ps -q --filter "label=com.docker.compose.project=$project" --filter "label=com.docker.compose.service=$role")
    if [[ -z "$existing" ]] || ! docker port "$existing" | grep -Fq "127.0.0.1:$port"; then
      echo "博客端口 $port 已被其他服务占用" >&2; exit 1
    fi
  fi
done
bash "$release/site.sh" "$release" check
if [[ -n "$previous_dir" ]]; then
  old=(docker compose --project-directory "$deploy_path" --env-file "$previous_dir/image.env" -p "$project" -f "$previous_dir/compose.production.yaml" -f "$previous_dir/runtime.compose.json")
  "${old[@]}" stop api
  app_stopped=true
  "${old[@]}" exec -T postgres pg_dump -U kidrue_blog -d kidrue_blog --format=custom > "$backup/database.dump"
  docker run --rm --user 0 --mount "type=volume,src=${project}_media,dst=/media,readonly" -v "$backup:/backup" "kidrue-blog-tools:$revision" tar -czf /backup/media.tar.gz -C /media .
fi
"${dc[@]}" up -d --no-build --wait --wait-timeout 120 postgres
install -d -m 700 "$deploy_path/.deploy/database"
cp "$release/runtime.json" "$deploy_path/.deploy/database/runtime.json"
gateway=$(docker network inspect "${project}_default" --format '{{(index .IPAM.Config 0).Gateway}}')
render "$gateway"
migration_started=true
"${dc[@]}" run --rm --no-deps -T migrate < /dev/null
"${dc[@]}" up -d --no-build --wait --wait-timeout 180 api web
curl -fsS --max-time 15 "http://127.0.0.1:$BLOG_API_PORT/api/health" >/dev/null
curl -fsS --max-time 15 "http://127.0.0.1:$BLOG_WEB_PORT/blog-release.json" >/dev/null
bash "$release/site.sh" "$release" prepare
printf '%s\n' '::kidrue::dns'
IFS= read -r -t 1200 response
test "$response" = DNS_OK
bash "$release/site.sh" "$release" tls
printf '%s\n' '::kidrue::verify'
IFS= read -r -t 900 response
test "$response" = VERIFY_OK
if [[ "$legacy_healthy" = true ]]; then curl -fsS --max-time 10 http://127.0.0.1:3000/health >/dev/null; fi
keep="$deploy_path/.deploy/keep-images"
if [[ -f "$keep" ]]; then head -n 4 "$keep" > "$release/previous-images"; else touch "$release/previous-images"; fi
for role in api web tools postgres; do printf 'kidrue-blog-%s:%s\n' "$role" "$revision"; done > "$keep.next"
cat "$release/previous-images" >> "$keep.next"
mv -f "$keep.next" "$keep"
ln -sfn "$release" "$deploy_path/.deploy/current.next"
mv -Tf "$deploy_path/.deploy/current.next" "$deploy_path/.deploy/current"
if ! bash "$release/cleanup-images.sh" "$deploy_path"; then echo '博客已部署，旧镜像清理未完成。' >&2; fi
rm -f -- "$incoming/images.tar.gz" "$incoming/release.tar.gz" "$incoming/release.sha256" "$incoming/deploy.sh" "$incoming/site.sh" "$incoming/cleanup-images.sh" "$incoming/compose.production.yaml"
rmdir "$incoming" || true
echo "部署成功：$revision https://$BLOG_DOMAIN；备份：$backup"
